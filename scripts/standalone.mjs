// Builds a self-contained copy of the home page: ./index.html
// All CSS, JS and the favicon are inlined, so the file can be opened directly in a browser
// (double-click / file://) or shared on its own — no server, no other files needed.
//
// Usage: npm run standalone   (builds the site first, then writes ./index.html)
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const DIST = 'dist';
const OUT = 'index.html';
const src = join(DIST, 'index.html');

if (!existsSync(src)) {
	console.error('dist/index.html not found — run `npm run build` first.');
	process.exit(1);
}

let html = readFileSync(src, 'utf8');

// 1. Inline stylesheets: <link rel="stylesheet" href="/_astro/x.css"> → <style>…</style>
let inlinedCss = 0;
html = html.replace(/<link rel="stylesheet" href="(\/[^"]+\.css)">/g, (_, href) => {
	const css = readFileSync(join(DIST, href), 'utf8');
	inlinedCss++;
	return `<style>${css}</style>`;
});

// 2. Inline the favicon as a data URI.
html = html.replace(/href="\/favicon\.svg"/, () => {
	const svg = readFileSync(join(DIST, 'favicon.svg'));
	return `href="data:image/svg+xml;base64,${svg.toString('base64')}"`;
});

// 3. Drop links that only make sense on the deployed server.
html = html
	.replace(/<link rel="sitemap"[^>]*>/, '')
	.replace(/<link rel="alternate" type="application\/rss\+xml"[^>]*>/, '');

// 4. Safety check: nothing external may remain (scripts are already inlined by Astro).
const leftovers = html.match(/<(?:link|script|img)[^>]+(?:href|src)="\/(?!\/)[^"]*\.(?:css|js|svg|png|jpe?g|webp)"/g);
if (leftovers) {
	console.error('Unexpected external resources remain:\n' + leftovers.join('\n'));
	process.exit(1);
}

const banner =
	'<!-- Standalone home page generated by `npm run standalone` from src/pages/index.astro. ' +
	'Do not edit by hand: change the source and regenerate. -->\n';
writeFileSync(OUT, html.replace(/^<!DOCTYPE html>/i, (m) => `${m}\n${banner}`));

console.log(`✔ Wrote ${OUT} (${(Buffer.byteLength(html) / 1024).toFixed(1)} KB, ${inlinedCss} stylesheet(s) inlined)`);
